// WRITES arena-client/known-good-clients.json: the known-good list of the
// scripts a page serves that decide money (§24, v4.6.2; F2's second clause: "a
// client whose hash is not on the known-good list cannot enter a paying
// round").
//
//   node packages/arena-client/tools/known-clients.js
//
// OUTSIDE THE BUNDLE IT DESCRIBES: a list inside `arena-client.js` would change
// the very hash it claims to pin. And it is checked OUTSIDE THE PAGE
// (`arena-node/tools/client-hash.mjs`), because a lying page passes any check it
// runs on itself.
//
// The three scripts are pinned from their build outputs, which Unity copies into
// a WebGL build byte for byte (no template macros in them). `index.html` is
// NOT pinned: Unity writes it from the template with build values filled in, so
// only a completed WebGL build can pin it - a later deploy pin. Hashes already
// listed stay listed; the current build's are added.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

const at = (p) => new URL(p, import.meta.url).pathname;
const OUT = at('../known-good-clients.json');
const SOURCES = {
  'arena-client.js': at('../dist/arena-client.js'),
  'arena-curve.js': at('../dist/arena-curve.js'),
  // THE LOCK CLIENT (W1b): the player's stake is locked by this code, so it
  // decides money. Its glue and its wasm, as wasm-bindgen wrote them.
  'blwp_lock_client.js': at('../dist/blwp_lock_client.js'),
  'blwp_lock_client_bg.wasm': at('../dist/blwp_lock_client_bg.wasm'),
};
// EACH GAME'S OWN SCRIPTS (one list per game), beside the engine's above.
const GAME_SOURCES = {
  nextblock: { 'blwp-core.js': at('../../nextblock/dist/blwp-core.js'),
    // ITS MARK: the icon, the wordmark, the favicon and app icons, the link preview - served beside the page
    ...Object.fromEntries(['nextblock-icon.svg', 'nextblock-wordmark.svg', 'favicon.ico', 'apple-touch-icon.png',
      'nextblock-icon-192.png', 'nextblock-icon-512.png', 'nextblock-og.png', 'site.webmanifest']
      .map((f) => [f, at(`../../nextblock/brand/${f}`)])) },
};
const sha = (p) => createHash('sha256').update(readFileSync(p)).digest('hex');

const prior = existsSync(OUT) ? JSON.parse(readFileSync(OUT, 'utf8')) : { pinned: {} };
const pinned = {};
for (const [name, path] of Object.entries(SOURCES)) {
  const now = sha(path);
  const was = (prior.pinned && prior.pinned[name]) || [];
  pinned[name] = was.includes(now) ? was : [...was, now];
  console.log(`${name.padEnd(15)} ${now} ${was.includes(now) ? 'already listed' : 'added'}`);
}
const games = {};
for (const [game, sources] of Object.entries(GAME_SOURCES)) {
  games[game] = { pinned: {} };
  for (const [name, path] of Object.entries(sources)) {
    const now = sha(path);
    const was = (prior.games && prior.games[game] && prior.games[game].pinned[name]) || [];
    games[game].pinned[name] = was.includes(now) ? was : [...was, now];
    console.log(`${game}/${name.padEnd(15)} ${now} ${was.includes(now) ? 'already listed' : 'added'}`);
  }
}
writeFileSync(OUT, JSON.stringify({
  what: 'sha256 of each script a page serves that decides money, the engine\'s under `pinned` and each game\'s under '
    + '`games` (one list per game); checked outside the page by arena-node/tools/client-hash.mjs. '
    + 'Generated by arena-client/tools/known-clients.js.',
  pinned,
  games,
  notPinned: {
    'index.html': 'Unity writes it from the template at build time; a completed WebGL build pins it',
  },
}, null, 1) + '\n');
