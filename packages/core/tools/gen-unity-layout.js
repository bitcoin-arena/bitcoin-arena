// Generates the C# view of the state layout FROM state.js.
//
// This exists because of the failure it prevents. C# and JavaScript both index
// the same ArrayBuffer by word offset, and if one of them thinks the truck's x
// is at word 5 while the other says 6, nothing throws - the truck simply
// renders somewhere wrong, or its health becomes its heading. A layout written
// twice by hand drifts the first time a field is inserted.
//
//   node tools/gen-unity-layout.js > ../../unity-proto/Assets/Scripts/Blwp/BlwpLayout.cs

import { readFileSync } from 'node:fs';

const src = readFileSync(new URL('../src/state.js', import.meta.url).pathname, 'utf8');

// Only the exported integer constants; anything else is not layout.
const consts = [];
for (const m of src.matchAll(/^export const ([A-Z][A-Z0-9_]*) = ([^;]+);/gm)) {
  const [, name, expr] = m;
  let value;
  if (/^\d+$/.test(expr)) value = Number(expr);
  else if (/^Math\.imul\((\w+),\s*(\w+)\)$/.test(expr)) continue;      // resolved below
  else if (/^[\w\s+*]+$/.test(expr)) value = null;                      // needs evaluation
  else continue;
  consts.push({ name, expr, value });
}

// Evaluate against the module itself rather than re-implementing the
// arithmetic - the whole point is that there is one source of truth.
const mod = await import(new URL('../src/state.js', import.meta.url));

const wanted = Object.keys(mod).filter(
  (k) => /^[A-Z][A-Z0-9_]*$/.test(k) && typeof mod[k] === 'number');

let out = '';
out += '// GENERATED by packages/core/tools/gen-unity-layout.js. Do not edit.\n';
out += '//\n';
out += '// The word offsets into the deterministic core\'s state buffer. Generated\n';
out += '// rather than written, because C# and JavaScript index the same ArrayBuffer\n';
out += '// and a disagreement about where a field lives does not throw - the truck\n';
out += '// just renders somewhere wrong, or its health becomes its heading.\n';
out += '\n';
out += 'namespace Blwp\n{\n';
out += '    /// <summary>Word offsets into the core state buffer. Generated from state.js.</summary>\n';
out += '    public static class Layout\n    {\n';
for (const k of wanted.sort()) out += `        public const int ${k} = ${mod[k]};\n`;
out += '\n';

// The spawn lives in sim.js, not state.js, but it has to reach C# for the same
// reason the offsets do: Unity draws a loading bay at one place and the core
// starts the truck at another, and nothing throws - the truck simply spawns
// inside the building and clips through it.
const sim = await import(new URL('../src/sim.js', import.meta.url));
out += '        /// <summary>Where the core starts the truck, Q16.16 metres.</summary>\n';
out += `        public const int START_X = ${sim.START_X};\n`;
out += `        public const int START_Z = ${sim.START_Z};\n`;
// THE HUD'S CHART (WAR_TACTICS.md §0.3) reaches C# the same way: the words of `chartView`'s output and the names the
// painter labels them with, so the page reads the core's chart and restates none of it.
const chart = await import(new URL('../src/chart.js', import.meta.url));
const tactics = await import(new URL('../src/rules/tactics.js', import.meta.url));
out += '\n        // chart view (src/chart.js) and the objective, holder and assault names it carries\n';
for (const k of Object.keys(chart).filter((k) => /^(CH_|CHART_)/.test(k) && typeof chart[k] === 'number').sort())
  out += `        public const int ${k} = ${chart[k]};\n`;
for (const k of Object.keys(tactics).filter((k) => /^(OBJ_|HOLDER_|ASSAULT_)/.test(k) && typeof tactics[k] === 'number').sort())
  out += `        public const int ${k} = ${tactics[k]};\n`;
out += '\n';
out += '        /// <summary>Base word offset of unit <paramref name="i"/>.</summary>\n';
out += '        public static int UnitBase(int i) => O_UNITS + i * U_WORDS;\n';
// The air needs the same, and for the same reason: a renderer that draws
// gunships and bombs from the core has to find them without restating the
// stride on the C# side.
out += '\n';
out += '        /// <summary>Base word offset of helicopter <paramref name="i"/>.</summary>\n';
out += '        public static int HeliBase(int i) => O_HELIS + i * H_WORDS;\n';
out += '\n';
out += '        /// <summary>Base word offset of bomb <paramref name="i"/>.</summary>\n';
out += '        public static int BombBase(int i) => O_BOMBS + i * B_WORDS;\n';
out += '    }\n}\n';

process.stdout.write(out);
