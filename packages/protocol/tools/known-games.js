// WRITES packages/protocol/src/known-games.js (kanban #202, §0A.6, §5): the games this client lets a player stake on -
// each by game_id, with the cores and configs its manifest lists - from each game's signed manifest. Replaces
// tools/known-cores.js: a known core is now a core of a known game.
//
//   node packages/protocol/tools/known-games.js
//
// Run it when a game's manifest changes (a new manifest is a new game_id; the old one stays listed, so a round already
// written on it is still known). And the configs whose rounds share one world (seed.js), as known-cores.js carried them.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { NEXTBLOCK_MANIFEST, NEXTBLOCK_GAME_ID } from '../../core/plugin/nextblock.js';
import { computeCurrentConfigHash, encodeGameConfigV4, GAME_CONFIG_V4, WORLD_SHARED_PER_ROUND } from '../src/genesis.js';
import { toHex } from '../src/hash.js';

const OUT = new URL('../src/known-games.js', import.meta.url).pathname;
const prior = existsSync(OUT) ? (await import(OUT)) : { KNOWN_GOOD_GAMES: {}, WORLD_SHARED_CONFIGS: [] };
const games = { ...prior.KNOWN_GOOD_GAMES };
for (const [id, m] of [[toHex(NEXTBLOCK_GAME_ID), NEXTBLOCK_MANIFEST]])
  games[id] = { name: m.gameName, cores: Object.fromEntries(m.cores.map((c) => [toHex(c.hash), c.configs.map(toHex)])) };

const v4 = encodeGameConfigV4();
const current = toHex(computeCurrentConfigHash());
const shared = [...new Set([...prior.WORLD_SHARED_CONFIGS, ...(v4[0] === GAME_CONFIG_V4 && v4[v4.length - 1] === WORLD_SHARED_PER_ROUND ? [current] : [])])];

writeFileSync(OUT, `// GENERATED by packages/protocol/tools/known-games.js from each game's signed manifest - do not edit by hand.
//
// The games this client lets a player stake on (§0A.6, §5; kanban #202), by game_id: each with the cores (sim_wasm_hash)
// and, per core, the configs its manifest lists. A paying round naming any other game, or a core or config its game does
// not list, is refused by \`gameIsKnownGood\` (known-game.js).
export const KNOWN_GOOD_GAMES = Object.freeze({
${Object.entries(games).map(([id, g]) => `  '${id}': Object.freeze({
    name: '${g.name}',
    cores: Object.freeze({
${Object.entries(g.cores).map(([c, cs]) => `      '${c}': Object.freeze([${cs.map((x) => `'${x}'`).join(', ')}]),`).join('\n')}
    }),
  }),`).join('\n')}
});

// The configs whose rounds share ONE world per round (§5A.5 round_seed; #23): seed.js derives every player's world from the
// round alone under these, and per player (as before) under every other config.
export const WORLD_SHARED_CONFIGS = Object.freeze([
${shared.map((h) => `  '${h}',`).join('\n')}
]);
`);
console.log(`${Object.keys(games).length} game(s) listed: ${Object.values(games).map((g) => g.name).join(', ')}`);
