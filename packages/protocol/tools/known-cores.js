// WRITES protocol/src/known-cores.js: the client's known-good list of core
// hashes (§5, v4.6: "for real-money rounds the client MUST verify the hash
// against its known-good list of reproducibly built core versions").
//
//   node packages/protocol/tools/known-cores.js
//
// The hash is `core/tools/hash-core.js`'s, computed now from the core sources,
// never typed. Cores already listed stay listed - a round created on one is
// still a round this client may join - and the current one is added if absent.
// Listing a new core is a deliberate act: `known-core.test.js` fails until it
// is done.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { coreHashHex } from '../../core/tools/hash-core.js';
import { computeCurrentConfigHash, computeGenesisConfigHash, computeDe2fConfigHash, computeConfigV3Hash, encodeGameConfigV4, GAME_CONFIG_V4, WORLD_SHARED_PER_ROUND } from '../src/genesis.js';
import { toHex } from '../src/hash.js';

const OUT = new URL('../src/known-cores.js', import.meta.url).pathname;
// the core list only - the file also holds the core+config pairs below it, whose config hashes are not cores
const priorList = existsSync(OUT) ? (readFileSync(OUT, 'utf8').split('KNOWN_GOOD_CORE_CONFIGS')[0]) : '';
const prior = [...priorList.matchAll(/'([0-9a-f]{64})'/g)].map((m) => m[1]);
const now = coreHashHex();
const list = prior.includes(now) ? prior : [...prior, now];

// AND THE CONFIGS EACH CORE'S ROUNDS MAY NAME (Daniel 2026-10-04, fix 1 of the spec audit): pairs, kept like the cores -
// listed ones stay listed, and the current core gets the config of the rules it plays (genesis.js encodeGameConfigV2).
// 2069b4c2 runs the founding config; de2f263d the current one, and the founding one for the rounds made before it had its own.
const FOUNDING = toHex(computeGenesisConfigHash());
const priorPairs = existsSync(OUT)
  ? Object.fromEntries([...readFileSync(OUT, 'utf8').matchAll(/^  '([0-9a-f]{64})': Object\.freeze\(\[([^\]]*)\]\)/gm)]
    .map((m) => [m[1], [...m[2].matchAll(/'([0-9a-f]{64})'/g)].map((x) => x[1])]))
  : {};
const pairs = { '2069b4c2ab39466c79000aac1b091c75b066b814a0952f8037011691538a774e': [FOUNDING],
  // the free rounds de2f263d played from 08:23Z with the founding config, before its own (the seats hold that pair only
  // for rounds made before 2026-10-04 13:00Z; the client takes the pair, the seats the date)
  'de2f263da7ddf892699713ccd43041fb2ea881df9994fbe9f32581904e32e6c8': [toHex(computeDe2fConfigHash()), FOUNDING], ...priorPairs };
const current = toHex(computeCurrentConfigHash());
// THE CURRENT CORE PLAYS BOTH CONFIGS THE TRUCK INSTALLS (blwp-node/src/cores.js TRUCK.configs, #23): v4, one world per round,
// and v3 (f51759b6), the per-player world older rounds and the tests whose rounds carry a world secret name. Listed for the
// current core as the seats install it for that core - a new core is not refused a config its seats play (kanban #29).
pairs[now] = [...new Set([current, toHex(computeConfigV3Hash()), ...(pairs[now] || [])])];

// AND THE CONFIGS WHOSE ROUNDS SHARE ONE WORLD (#23, Daniel 2026-10-04): listed ones stay, the current one joins if its
// encoding is v4 with the world rule 1 - seed.js reads this list, so the page and the seats choose by the same hash.
const priorShared = existsSync(OUT)
  ? [...((readFileSync(OUT, 'utf8').split('WORLD_SHARED_CONFIGS')[1] || '').matchAll(/'([0-9a-f]{64})'/g))].map((m) => m[1]) : [];
const v4 = encodeGameConfigV4();
const shared = [...new Set([...priorShared, ...(v4[0] === GAME_CONFIG_V4 && v4[v4.length - 1] === WORLD_SHARED_PER_ROUND ? [current] : [])])];

writeFileSync(OUT, `// GENERATED by packages/protocol/tools/known-cores.js from
// packages/core/tools/hash-core.js - do not edit by hand.
//
// The core hashes (sim_wasm_hash, sorted-source sha256) of reproducibly built
// core versions this client will let a player stake on (§5). A paying round
// naming any other core is refused by \`coreIsKnownGood\` (known-core.js).
export const KNOWN_GOOD_CORE_HASHES = Object.freeze([
${list.map((h) => `  '${h}',`).join('\n')}
]);

// The configs a round on each of these cores may name (§27A.6: a round names the config of the rules it plays). A core
// with no entry here is checked by its hash alone, as before pairs were listed.
export const KNOWN_GOOD_CORE_CONFIGS = Object.freeze({
${Object.entries(pairs).map(([c, cs]) => `  '${c}': Object.freeze([${cs.map((x) => `'${x}'`).join(', ')}]),`).join('\n')}
});

// The configs whose rounds share ONE world per round (§5A.5 round_seed; #23): seed.js derives every player's world from the
// round alone under these, and per player (as before) under every other config.
export const WORLD_SHARED_CONFIGS = Object.freeze([
${shared.map((h) => `  '${h}',`).join('\n')}
]);
`);
console.log(`core ${now} ${prior.includes(now) ? 'already listed' : 'added'}; ${list.length} listed`);
