#!/usr/bin/env node
/**
 * TESTNET4'S DONATION SET OF KEYS (Daniel 2026-10-03, FEDERATION.md "Donations in the federation"): "Every dev has its own
 * client with a private key that corresponds to the 66.67% or 33.33% stake in the donation set."
 *
 *   DONOR_DIRS=<dir a>,<dir b> VALID_FROM=<height> node packages/protocol/tools/sign-testnet4-key-donation-set.mjs
 *
 * Reads each dev client's PUBLIC key from its donor.json (packages/blwp-donor init; the secret stays in its key.json), and
 * signs with testnet4's donation authority (refused if the key is not the one genesis names) a set of keys with serial 3 -
 * above the LNURL sets' 1 and 2, so from VALID_FROM on it is the set in force (27A.4) and every round written from there
 * names it. Shares 6667 / 3333 in that order (the remainder to the first). Writes src/testnet4-donation-set-keys.js -
 * PUBLIC BYTES ONLY.
 */
import { createPrivateKey, createPublicKey, sign, verify } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { toHex, fromHex } from '../src/hash.js';
import { NETWORK_ID_TESTNET4, AUTHORITY_PUBKEY_TESTNET4 } from '../src/genesis-ids.js';
import { encodeDonationSetBody, decodeDonationSetBody, donationSetBodyId } from '../src/authority.js';
import { donationSetId } from '../src/donation.js';

const KEYDIR = process.env.BLWP_GENESIS_KEYS || '/mnt/bitcoin/blwp-genesis';
const OUT = new URL('../src/testnet4-donation-set-keys.js', import.meta.url);
const dirs = String(process.env.DONOR_DIRS || '').split(',').filter(Boolean);
if (dirs.length !== 2) throw new Error('DONOR_DIRS names the two dev clients, dev a then dev b');
const VALID_FROM = Number(process.env.VALID_FROM);
if (!Number.isInteger(VALID_FROM) || VALID_FROM < 1) throw new Error('VALID_FROM is the block height the set is in force from');
const SHARES = [6667, 3333];
const RECIPIENTS = dirs.map((d, i) => {
  const c = JSON.parse(readFileSync(join(d, 'donor.json'), 'utf8'));
  return { recipientPk: fromHex(c.recipientPkHex), shareBps: SHARES[i], label: String(c.label || `dev ${i}`) };
});

const key = createPrivateKey({ key: readFileSync(join(KEYDIR, 'testnet4-authority.pkcs8')), format: 'der', type: 'pkcs8' });
if (key.asymmetricKeyType !== 'ed25519') throw new Error('the testnet4 donation authority key is not Ed25519');
const pub = createPublicKey(key);
if (toHex(pub.export({ type: 'spki', format: 'der' }).subarray(-32)) !== toHex(AUTHORITY_PUBKEY_TESTNET4))
  throw new Error('that key is not the donation authority testnet4 genesis names');
const body = { networkId: NETWORK_ID_TESTNET4, serial: 3n, validFrom: VALID_FROM, recipients: RECIPIENTS };
const bytes = encodeDonationSetBody(body);
const digest = Buffer.from(donationSetBodyId(body));
const signature = sign(null, digest, key);
if (!verify(null, digest, pub, signature)) throw new Error('the signature does not verify');
decodeDonationSetBody(bytes);
writeFileSync(OUT, `// Generated by tools/sign-testnet4-key-donation-set.mjs. PUBLIC BYTES ONLY: testnet4's donation set of KEYS (Daniel
// 2026-10-03, FEDERATION.md "Donations in the federation"), signed offline by testnet4's Ed25519 donation authority, serial 3,
// in force from block ${VALID_FROM}. Each recipient is a dev client's key (packages/blwp-donor); its secret stays with it.
import { fromHex } from './hash.js';
import { decodeDonationSetBody } from './authority.js';

export const TESTNET4_DONATION_SET_KEYS = { ...decodeDonationSetBody(fromHex('${toHex(bytes)}')),
  signature: fromHex('${toHex(signature)}') };
`);
console.log(JSON.stringify({ serial: 3, validFrom: VALID_FROM, setId: toHex(donationSetId(RECIPIENTS)), recipients: RECIPIENTS.map((r) => [r.label, toHex(r.recipientPk), r.shareBps]), wrote: OUT.pathname }));
