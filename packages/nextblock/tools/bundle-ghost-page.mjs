// TICK TOCK'S GHOSTS, AS ITS OWN PAGE SCRIPT (§0A.2 "the engine never imports a game's code"; kanban #521/#525): page/ghost-field.js
// is what the page does with a picture of somebody else's truck - only Tick Tock's Unity bridge (arena.jslib) and its page part ask
// for it. It was walked into the engine's client bundle (arena-client.js); it is now page/ghost-page.js, a classic script the page
// loads after the bundle, which puts its exports on ARENACLIENT where the jslib has always called them. Its two helpers come from
// the bundle (toHex; generatedName is displayNameFromKey). Nothing is transformed: the import lines go, `export ` goes, the rest is
// the module's text.
//     node packages/nextblock/tools/bundle-ghost-page.mjs [--check]
import { readFileSync, writeFileSync } from 'node:fs';

const SRC = new URL('../page/ghost-field.js', import.meta.url);
const OUT = new URL('../page/ghost-page.js', import.meta.url);

export function ghostPage() {
  const text = readFileSync(SRC, 'utf8');
  const imports = [...text.matchAll(/^import\s[\s\S]*?from\s+'([^']+)';\n/gm)];
  const allowed = new Set(['arena-sdk/hash', 'arena-sdk/display-name']);   // the Arena through arena-sdk (kanban #568)
  for (const m of imports) if (!allowed.has(m[1])) throw new Error(`ghost-field.js imports ${m[1]}, which the page script does not bring`);
  const body = text.replace(/^import\s[\s\S]*?from\s+'[^']+';\n/gm, '').replace(/^export\s+/gm, '');
  const names = [...text.matchAll(/^export\s+(?:async\s+)?(?:const|function|let|class)\s+([A-Za-z_$][\w$]*)/gm)].map((m) => m[1]);
  const head = body.match(/^(\/\/ SPDX[^\n]*\n\/\/ Copyright[^\n]*\n)/);
  if (!head) throw new Error('ghost-field.js does not start with its license lines');
  return head[1] + '// GENERATED by packages/nextblock/tools/bundle-ghost-page.mjs from page/ghost-field.js. Do not edit.\n'
    + '(function () {\n"use strict";\n'
    + 'const toHex = window.ARENACLIENT.toHex;\nconst displayNameFromKey = window.ARENACLIENT.generatedName;\n'
    + body.slice(head[1].length)
    + `\nObject.assign(window.ARENACLIENT, { ${names.join(', ')} });\n})();\n`;
}

if (process.argv[1] === new URL(import.meta.url).pathname) {
  const want = ghostPage();
  if (process.argv.includes('--check')) {
    let have = ''; try { have = readFileSync(OUT, 'utf8'); } catch { /* none yet */ }
    if (have !== want) { console.error('page/ghost-page.js is not the build of page/ghost-field.js: run tools/bundle-ghost-page.mjs'); process.exit(1); }
    console.log('page/ghost-page.js is the build of page/ghost-field.js');
  } else { writeFileSync(OUT, want); console.log('wrote page/ghost-page.js'); }
}
