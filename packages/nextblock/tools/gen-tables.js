// Run ONCE, by a human, and commit the output.
//
// Generating src/tables.js at startup with Math.sin would reintroduce exactly
// the cross-engine dependence this whole design exists to avoid: the table
// would differ by one ULP between Chrome and Safari, and the divergence would
// surface only after minutes of play. The determinism guard fails the build if
// tables.js is ever produced as part of one.
//
//   node tools/gen-tables.js > src/tables.js

const QUARTER = 4096;                 // entries in the quarter wave
const ONE = 65536;

const rows = [];
for (let i = 0; i <= QUARTER; i++) {
  // i / QUARTER of a quarter turn
  const v = Math.round(Math.sin((i / QUARTER) * (Math.PI / 2)) * ONE);
  rows.push(v);
}

let out = '';
out += '// GENERATED by tools/gen-tables.js. Do not edit, do not regenerate in a\n';
out += '// build step - see the note in that file. Committed on purpose.\n';
out += '//\n';
out += '// Quarter sine wave, ' + QUARTER + ' + 1 entries, values in Q16.16.\n';
out += 'export const QUARTER = ' + QUARTER + ';\n';
out += 'export const SIN_Q = new Int32Array([\n';
for (let i = 0; i < rows.length; i += 12) {
  out += '  ' + rows.slice(i, i + 12).join(', ') + ',\n';
}
out += ']);\n';
process.stdout.write(out);
