// NEXTBLOCK'S MANIFEST VERSION 4, SIGNED BY ITS DEVELOPER (2026-10-16: "Go" on (A) - a game version decides
// an item's terms): version 3 in every term - its cores, its clients, its items (the larger truck, 500 sat) - requiring protocol
// version 11, so its items sell on the protocol reserves' terms (nodes 40 %, reserves 20 %, the developers 40/30/20/10/0 %).
// Version 3 keeps 's terms beside it. Parent: version 3 (plugin/nextblock-v3.js).
//
//   node packages/nextblock/tools/sign-manifest-v4.mjs <dev dir holding game-dev.pkcs8>
//
// Writes only public bytes: plugin/nextblock-v4.js.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { gameDevKey, signManifest } from 'arena-sdk/manifest-sign';
import { MANIFEST_V3, GAME_ID_V3 } from '../plugin/nextblock-v3.js';
import { encodeManifest, gameIdOf, manifestStands } from 'arena-sdk/manifest';
import { RESERVES_VERSION } from 'arena-sdk/constants';
import { toHex } from 'arena-sdk/hash';
import { verifyEd25519 } from 'arena-sdk/ed25519';

const [dir] = process.argv.slice(2);
if (!dir) { console.error('usage: node sign-manifest-v4.mjs <dev dir holding game-dev.pkcs8>'); process.exit(2); }
const dev = gameDevKey(readFileSync(join(dir, 'game-dev.pkcs8')));
if (toHex(dev.pubkey) !== toHex(MANIFEST_V3.gameDevPubkey)) throw new Error(`that key is not nextblock's developer key ${toHex(MANIFEST_V3.gameDevPubkey).slice(0, 16)}`);
const { signature, ...v3body } = MANIFEST_V3;
void signature;
const body = { ...v3body, version: MANIFEST_V3.version + 1, parentManifestId: GAME_ID_V3, requiredProtocolVersion: RESERVES_VERSION };
const manifest = signManifest(body, dev);
const stands = manifestStands(manifest, { verify: verifyEd25519, parentOf: (id) => (toHex(id) === toHex(GAME_ID_V3) ? MANIFEST_V3 : null) });
if (!stands.ok) throw new Error(stands.why);
const id = toHex(gameIdOf(manifest));
writeFileSync(new URL('../plugin/nextblock-v4.js', import.meta.url), `// GENERATED by packages/nextblock/tools/sign-manifest-v4.mjs with the dev client's signer - do not edit by hand. PUBLIC BYTES ONLY:
// nextblock's GameManifest version 4: version 3 (${toHex(GAME_ID_V3)}) in every term, requiring protocol
// version ${RESERVES_VERSION}: its items sell on the protocol reserves' terms. Signed by its developer key ${toHex(dev.pubkey)}; a node verifies it.
// game_id ${id}
import { GAME as V1 } from './nextblock.js';
import { NEXTBLOCK_CORES_V3 } from './truck-cores.js';
import { decodeManifest, gameIdOf } from 'arena-sdk/manifest';
import { fromHex } from 'arena-sdk/hash';

export const MANIFEST_V4_HEX = '${toHex(encodeManifest(manifest))}';
export const MANIFEST_V4 = decodeManifest(fromHex(MANIFEST_V4_HEX));
export const GAME_ID_V4 = gameIdOf(MANIFEST_V4);
/** What a launcher loads from this module (ARENA_GAMES): the registration. */
export const GAME = Object.freeze({ ...V1, manifest: MANIFEST_V4, gameId: GAME_ID_V4, cores: NEXTBLOCK_CORES_V3 });
`);
console.log(`nextblock v${body.version}: parent ${toHex(GAME_ID_V3).slice(0, 16)}, ${body.cores.length} cores, ${body.clients.length} clients, items ${body.items.map((i) => `${i.id} ${i.priceSat} sat`).join(', ')}, protocol ${body.requiredProtocolVersion}; game_id ${id}`);
