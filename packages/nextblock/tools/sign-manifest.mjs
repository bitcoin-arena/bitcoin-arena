// NEXTBLOCK'S MANIFEST, SIGNED BY ITS DEVELOPER WITH THE DEV CLIENT (2026-10-07 15:40; moved here from
// arena-donor/bin by: the body is nextblock's, so the step is the game's, and the engine imports no game). It calls the
// dev client's signer (arena-donor/src/manifest-sign.js) with the game developer's key, held in the dev client's own
// directory, and writes only public bytes - the body (with the public key) and the signature - into this package. Run by
// the game's developer, never on a seat; a seat only verifies.
//
//   node packages/nextblock/tools/sign-manifest.mjs <dev dir>
//
// The key is <dev dir>/game-dev.pkcs8 (Ed25519, PKCS#8 DER, mode 600). For nextblock the body is its registration's own
// (core/plugin/truck-cores.js nextblockManifestBody): every installed core with its configs, the game's client files
// (its core script and, since, its mark: icons, wordmark, link preview) as arena-client/known-good-clients.json
// lists them for nextblock, and the donation set the testnet4 series name. Run it
// again whenever a core, a config or a client of nextblock changes: an update is a new manifest (§0A.3), and
// core/test/nextblock-manifest.test.js is red until the signed bytes are the registration's.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { gameDevKey, signManifest } from 'arena-sdk/manifest-sign';
import { nextblockManifestBody } from '../plugin/truck-cores.js';
import { encodeManifest, gameIdOf, manifestStands } from 'arena-sdk/manifest';
import { donationSetId } from 'arena-sdk/donation';
import { TESTNET4_DONATION_SET_KEYS } from 'arena-sdk/testnet4-donation-set-keys';
import { toHex } from 'arena-sdk/hash';
import { verifyEd25519 } from 'arena-sdk/ed25519';

const [dir] = process.argv.slice(2);
if (!dir) {
  console.error('usage: node sign-manifest.mjs <dev dir holding game-dev.pkcs8>');
  process.exit(2);
}
const dev = gameDevKey(readFileSync(join(dir, 'game-dev.pkcs8')));
const CLIENTS = JSON.parse(readFileSync(new URL('../plugin/clients.json', import.meta.url), 'utf8'));   // the app's own list (kanban #569)
const body = nextblockManifestBody({ clients: Object.values(CLIENTS.pinned).flat(), gameDevPubkey: dev.pubkey,
  gameDonationSetId: donationSetId(TESTNET4_DONATION_SET_KEYS.recipients) });
const manifest = signManifest(body, dev);
// AS A NODE WILL CHECK IT: the same verifier, the same rule
const stands = manifestStands(manifest, { verify: verifyEd25519 });
if (!stands.ok) throw new Error(stands.why);

const OUT = new URL('../plugin/nextblock-manifest.js', import.meta.url);
writeFileSync(OUT, `// GENERATED by packages/nextblock/tools/sign-manifest.mjs with the dev client's signer - do not edit by hand. PUBLIC BYTES ONLY:
// nextblock's GameManifest (§0A.3), its body and the 64-byte signature by its developer key
// ${toHex(dev.pubkey)}.
// A node verifies this signature (arena-node/src/plugins.js); it never holds the key and never signs.
// game_id ${toHex(gameIdOf(manifest))}
export const NEXTBLOCK_MANIFEST_HEX = '${toHex(encodeManifest(manifest))}';
`);
console.log(`nextblock v${body.version}: ${body.cores.length} cores, ${body.clients.length} clients; game_id ${toHex(gameIdOf(manifest))}`);
