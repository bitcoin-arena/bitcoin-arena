// NEXTBLOCK'S MANIFEST VERSION 3, SIGNED BY ITS DEVELOPER (the first in-game item of): the game as version 2 has it,
// with every core the node installs for it now (the truck that knows the larger truck among them), and its item catalogue - the larger
// truck for 500 sat - which requires protocol version 10. Its parent is version 2 (plugin/nextblock-v2.js), so a node keeps both.
//
//   node packages/nextblock/tools/sign-manifest-v3.mjs <dev dir>
//
// The key is <dev dir>/game-dev.pkcs8, the same developer key as versions 1 and 2. Writes only public bytes: plugin/nextblock-v3.js.
// Run it again whenever a core, a config, a client or an item of nextblock changes.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { gameDevKey, signManifest } from 'arena-sdk/manifest-sign';
import { nextblockManifestBody, NEXTBLOCK_ITEMS, NEXTBLOCK_CORES_V3 } from '../plugin/truck-cores.js';
import { MANIFEST_V2, GAME_ID_V2 } from '../plugin/nextblock-v2.js';
import { encodeManifest, gameIdOf, manifestStands } from 'arena-sdk/manifest';
import { donationSetId } from 'arena-sdk/donation';
import { TESTNET4_DONATION_SET_KEYS } from 'arena-sdk/testnet4-donation-set-keys';
import { ITEMS_VERSION } from 'arena-sdk/constants';
import { toHex, fromHex } from 'arena-sdk/hash';
import { verifyEd25519 } from 'arena-sdk/ed25519';
import { LARGE_TRUCK_UNLOCK } from '../frozen/f0cc7b7b/items.js';

const [dir] = process.argv.slice(2);
if (!dir) { console.error('usage: node sign-manifest-v3.mjs <dev dir holding game-dev.pkcs8>'); process.exit(2); }
const dev = gameDevKey(readFileSync(join(dir, 'game-dev.pkcs8')));
if (toHex(dev.pubkey) !== toHex(MANIFEST_V2.gameDevPubkey)) throw new Error(`that key is not nextblock's developer key ${toHex(MANIFEST_V2.gameDevPubkey).slice(0, 16)}`);
const LIST = JSON.parse(readFileSync(new URL('../../arena-client/known-good-clients.json', import.meta.url), 'utf8'));
const body = {
  ...nextblockManifestBody({ clients: Object.values(LIST.games.nextblock.pinned).flat(), gameDevPubkey: dev.pubkey,
    gameDonationSetId: donationSetId(TESTNET4_DONATION_SET_KEYS.recipients), cores: NEXTBLOCK_CORES_V3 }),
  version: MANIFEST_V2.version + 1,
  parentManifestId: GAME_ID_V2,
  items: NEXTBLOCK_ITEMS.map((it) => ({ ...it })),
  requiredProtocolVersion: ITEMS_VERSION,
};
const manifest = signManifest(body, dev);
// AS A NODE WILL CHECK IT: the same verifier, the same rule, its parent known
const stands = manifestStands(manifest, { verify: verifyEd25519, parentOf: (id) => (toHex(id) === toHex(GAME_ID_V2) ? MANIFEST_V2 : null) });
if (!stands.ok) throw new Error(stands.why);

const OUT = new URL('../plugin/nextblock-v3.js', import.meta.url);
const id = toHex(gameIdOf(manifest));
writeFileSync(OUT, `// GENERATED by packages/nextblock/tools/sign-manifest-v3.mjs with the dev client's signer - do not edit by hand. PUBLIC BYTES ONLY:
// nextblock's GameManifest version 3: parent ${toHex(GAME_ID_V2)} (version 2), every core the node installs for it,
// and its items - the larger truck for 500 sat, unlock ${LARGE_TRUCK_UNLOCK} - so it requires protocol version ${ITEMS_VERSION}.
// Signed by its developer key ${toHex(dev.pubkey)}; a node verifies it and never signs.
// game_id ${id}
import { GAME as V1 } from './nextblock.js';
import { NEXTBLOCK_CORES_V3 } from './truck-cores.js';
import { decodeManifest, gameIdOf } from 'arena-sdk/manifest';
import { fromHex } from 'arena-sdk/hash';

export const MANIFEST_V3_HEX = '${toHex(encodeManifest(manifest))}';
export const MANIFEST_V3 = decodeManifest(fromHex(MANIFEST_V3_HEX));
export const GAME_ID_V3 = gameIdOf(MANIFEST_V3);
/** What a launcher loads from this module (ARENA_GAMES): the registration. */
export const GAME = Object.freeze({ ...V1, manifest: MANIFEST_V3, gameId: GAME_ID_V3, cores: NEXTBLOCK_CORES_V3 });
`);
console.log(`nextblock v${body.version}: parent ${toHex(GAME_ID_V2).slice(0, 16)}, ${body.cores.length} cores (${body.cores.map((c) => toHex(c.hash).slice(0, 8)).join(' ')}), ${body.clients.length} clients, items ${body.items.map((i) => `${i.id} ${i.priceSat} sat`).join(', ')}, protocol ${body.requiredProtocolVersion}; game_id ${id}`);
