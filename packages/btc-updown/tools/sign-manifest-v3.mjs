// BITCOIN UP OR DOWN'S MANIFEST VERSION 3, SIGNED BY ITS DEVELOPER (2026-10-16: "Go. Add the back-to-games overview
// control on bitcoin up or down, same place and behavior as the Rock Paper Scissors header"): the market as version 2 has it in
// every term, with its new client (the back button on its own row, the title on its own line) beside version 2's, so either file
// runs a round of it. Its parent is version 2 (plugin/btc-updown-v2.js); it requires the protocol version 2 does.
//
//   node packages/btc-updown/tools/sign-manifest-v3.mjs <dev dir holding game-dev.pkcs8>
//
// Writes only public bytes: plugin/btc-updown-v3.js.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { gameDevKey, signManifest } from 'arena-sdk/manifest-sign';
import { MANIFEST_V2, GAME_ID_V2 } from '../plugin/btc-updown-v2.js';
import { encodeManifest, gameIdOf, manifestStands } from 'arena-sdk/manifest';
import { toHex } from 'arena-sdk/hash';
import { verifyEd25519 } from 'arena-sdk/ed25519';
import { UPDOWN_CLIENT_HASH, UPDOWN_CLIENT_V3_HASH } from '../plugin/market-terms.js';

const [dir] = process.argv.slice(2);
if (!dir) { console.error('usage: node sign-manifest-v3.mjs <dev dir holding game-dev.pkcs8>'); process.exit(2); }
const dev = gameDevKey(readFileSync(join(dir, 'game-dev.pkcs8')));
if (toHex(dev.pubkey) !== toHex(MANIFEST_V2.gameDevPubkey)) throw new Error(`that key is not Up/Down's developer key ${toHex(MANIFEST_V2.gameDevPubkey).slice(0, 16)}`);
if (toHex(MANIFEST_V2.clients[0]) !== toHex(UPDOWN_CLIENT_HASH)) throw new Error('client/index-v2.html is not the file version 2 pins');
const { signature, ...v2body } = MANIFEST_V2;
void signature;
const body = { ...v2body, version: MANIFEST_V2.version + 1, parentManifestId: GAME_ID_V2,
  clients: [new Uint8Array(UPDOWN_CLIENT_V3_HASH), new Uint8Array(UPDOWN_CLIENT_HASH)].sort((x, y) => Buffer.compare(Buffer.from(x), Buffer.from(y))) };   // a manifest lists them in byte order
const manifest = signManifest(body, dev);
const stands = manifestStands(manifest, { verify: verifyEd25519, parentOf: (id) => (toHex(id) === toHex(GAME_ID_V2) ? MANIFEST_V2 : null) });
if (!stands.ok) throw new Error(stands.why);
const id = toHex(gameIdOf(manifest));
writeFileSync(new URL('../plugin/btc-updown-v3.js', import.meta.url), `// GENERATED by packages/btc-updown/tools/sign-manifest-v3.mjs with the dev client's signer - do not edit by hand. PUBLIC BYTES ONLY:
// btc-updown-15m's GameManifest version 3: version 2 (${toHex(GAME_ID_V2)}) in every term, with the new client
// ${toHex(UPDOWN_CLIENT_V3_HASH)} beside version 2's ${toHex(UPDOWN_CLIENT_HASH)}; requires protocol version ${body.requiredProtocolVersion}.
// Signed by its developer key ${toHex(dev.pubkey)}; a node verifies it and never signs.
// game_id ${id}
import { GAME as V1 } from './btc-updown.js';
import { decodeManifest, gameIdOf } from 'arena-sdk/manifest';
import { fromHex } from 'arena-sdk/hash';

export const MANIFEST_V3_HEX = '${toHex(encodeManifest(manifest))}';
export const MANIFEST_V3 = decodeManifest(fromHex(MANIFEST_V3_HEX));
export const GAME_ID_V3 = gameIdOf(MANIFEST_V3);
/** What a launcher loads from this module (ARENA_APPS): the registration. */
export const GAME = Object.freeze({ ...V1, manifest: MANIFEST_V3, gameId: GAME_ID_V3 });
`);
console.log(`btc-updown-15m v${body.version}: parent ${toHex(GAME_ID_V2).slice(0, 16)}, clients ${body.clients.map((c) => toHex(c).slice(0, 8)).join(' ')}, game_id ${id}`);
