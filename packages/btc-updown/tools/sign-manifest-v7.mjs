// BITCOIN UP OR DOWN'S MANIFEST VERSION 7, SIGNED BY ITS DEVELOPER (2026-10-17: "also show closed orders with the
// history with how much you won or lost, and also show there if it's still pending (10 minute delay)"): version 6 in every term, with
// its new client - the history - beside version 6's and the older ones, so any of them runs a round of it. Parent: version 6.
//
//   node packages/btc-updown/tools/sign-manifest-v7.mjs <dev dir holding game-dev.pkcs8>
//
// Writes only public bytes: plugin/btc-updown-v7.js.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { gameDevKey, signManifest } from 'arena-sdk/manifest-sign';
import { MANIFEST_V6 as MANIFEST_V2, GAME_ID_V6 as GAME_ID_V2 } from '../plugin/btc-updown-v6.js';
import { encodeManifest, gameIdOf, manifestStands } from 'arena-sdk/manifest';
import { toHex } from 'arena-sdk/hash';
import { verifyEd25519 } from 'arena-sdk/ed25519';
import { UPDOWN_CLIENT_V6_HASH as UPDOWN_CLIENT_HASH, UPDOWN_CLIENT_V7_HASH as UPDOWN_CLIENT_V3_HASH } from '../plugin/market-terms.js';

const [dir] = process.argv.slice(2);
if (!dir) { console.error('usage: node sign-manifest-v7.mjs <dev dir holding game-dev.pkcs8>'); process.exit(2); }
const dev = gameDevKey(readFileSync(join(dir, 'game-dev.pkcs8')));
if (toHex(dev.pubkey) !== toHex(MANIFEST_V2.gameDevPubkey)) throw new Error(`that key is not Up/Down's developer key ${toHex(MANIFEST_V2.gameDevPubkey).slice(0, 16)}`);
if (!MANIFEST_V2.clients.some((c) => toHex(c) === toHex(UPDOWN_CLIENT_HASH))) throw new Error('client/index-v6.html is not a file version 6 pins');
const { signature, ...v2body } = MANIFEST_V2;
void signature;
const body = { ...v2body, version: MANIFEST_V2.version + 1, parentManifestId: GAME_ID_V2,
  clients: [...new Map([new Uint8Array(UPDOWN_CLIENT_V3_HASH), ...MANIFEST_V2.clients].map((c) => [toHex(c), c])).values()].sort((x, y) => Buffer.compare(Buffer.from(x), Buffer.from(y))) };   // the new one and version 3's, in byte order
const manifest = signManifest(body, dev);
const stands = manifestStands(manifest, { verify: verifyEd25519, parentOf: (id) => (toHex(id) === toHex(GAME_ID_V2) ? MANIFEST_V2 : null) });
if (!stands.ok) throw new Error(stands.why);
const id = toHex(gameIdOf(manifest));
writeFileSync(new URL('../plugin/btc-updown-v7.js', import.meta.url), `// GENERATED by packages/btc-updown/tools/sign-manifest-v7.mjs with the dev client's signer - do not edit by hand. PUBLIC BYTES ONLY:
// btc-updown-15m's GameManifest version 7: version 6 (${toHex(GAME_ID_V2)}) in every term, with the new client
// ${toHex(UPDOWN_CLIENT_V3_HASH)} (the history) beside version 6's; requires protocol version ${body.requiredProtocolVersion}.
// Signed by its developer key ${toHex(dev.pubkey)}; a node verifies it and never signs.
// game_id ${id}
import { GAME as V1 } from './btc-updown.js';
import { decodeManifest, gameIdOf } from 'arena-sdk/manifest';
import { fromHex } from 'arena-sdk/hash';

export const MANIFEST_V7_HEX = '${toHex(encodeManifest(manifest))}';
export const MANIFEST_V7 = decodeManifest(fromHex(MANIFEST_V7_HEX));
export const GAME_ID_V7 = gameIdOf(MANIFEST_V7);
/** What a launcher loads from this module (ARENA_APPS): the registration. */
export const GAME = Object.freeze({ ...V1, manifest: MANIFEST_V7, gameId: GAME_ID_V7 });
`);
console.log(`btc-updown-15m v${body.version}: parent ${toHex(GAME_ID_V2).slice(0, 16)}, clients ${body.clients.map((c) => toHex(c).slice(0, 8)).join(' ')}, game_id ${id}`);
