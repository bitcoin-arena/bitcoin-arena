#!/usr/bin/env node
/**
 * SIGN THE TEST NETWORKS' DONATION SETS, ONCE, OFFLINE (M3.2 item 6e; Daniel
 * 2026-09-13: the donation authority signs with Ed25519).
 *
 *   node packages/arena-protocol/tools/sign-donation-set.mjs
 *
 * Reads the regtest and testnet4 donation AUTHORITY keys that make-genesis.mjs
 * wrote (ARENA_GENESIS_KEYS, default /mnt/bitcoin/blwp-genesis), refuses a key
 * whose public half is not the one genesis hashes into the network id, signs
 * one test set for each network, checks its own signature, and writes
 * src/test-donation-sets.js - PUBLIC BYTES ONLY. Tests and launchers read that
 * file; none of them ever needs a secret.
 *
 * The recipients are two LOCAL TEST LNURL endpoints at a fixed address, so the
 * split between two recipients is exercised - never a production recipient.
 * Shares 6667 / 3333, so a 2000 msat donation also exercises §22A's rounding:
 * floor each share, the remainder to the first recipient as published.
 */
import { createPrivateKey, createPublicKey, sign, verify } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { toHex } from '../src/hash.js';
import {
  NETWORK_ID_REGTEST, NETWORK_ID_TESTNET4, AUTHORITY_PUBKEY_REGTEST, AUTHORITY_PUBKEY_TESTNET4,
} from '../src/genesis-ids.js';
import { encodeDonationSetBody, donationSetBodyId } from '../src/authority.js';
import { lnurlFor } from '../src/bech32.js';

const KEYDIR = process.env.ARENA_GENESIS_KEYS || '/mnt/bitcoin/blwp-genesis';
const OUT = new URL('../src/test-donation-sets.js', import.meta.url);
const BASE = 'http://127.0.0.1:18777/lnurlp/';
const ENDPOINTS = [`${BASE}blwp-test-a`, `${BASE}blwp-test-b`];
const RECIPIENTS = [
  { lnurl: lnurlFor(ENDPOINTS[0]), shareBps: 6667 },
  { lnurl: lnurlFor(ENDPOINTS[1]), shareBps: 3333 },
];

const signed = {};
for (const [name, networkId, authority] of [
  ['regtest', NETWORK_ID_REGTEST, AUTHORITY_PUBKEY_REGTEST],
  ['testnet4', NETWORK_ID_TESTNET4, AUTHORITY_PUBKEY_TESTNET4],
]) {
  const key = createPrivateKey({ key: readFileSync(join(KEYDIR, `${name}-authority.pkcs8`)), format: 'der', type: 'pkcs8' });
  if (key.asymmetricKeyType !== 'ed25519') throw new Error(`${name}: the donation authority key is not Ed25519`);
  const pub = createPublicKey(key);
  const derived = pub.export({ type: 'spki', format: 'der' }).subarray(-32);
  if (toHex(derived) !== toHex(authority))
    throw new Error(`${name}: that key is not the donation authority genesis names (${toHex(authority).slice(0, 16)})`);
  const body = { networkId, serial: 1n, validFrom: 0, recipients: RECIPIENTS };
  const digest = Buffer.from(donationSetBodyId(body));
  const signature = sign(null, digest, key);
  if (!verify(null, digest, pub, signature)) throw new Error(`${name}: the signature does not verify`);
  signed[name] = { body: toHex(encodeDonationSetBody(body)), signature: toHex(signature) };
  console.log(`${name.padEnd(8)} set signed by ${toHex(authority).slice(0, 16)}: ${signed[name].signature.slice(0, 16)}...`);
}

writeFileSync(OUT, `// Generated by tools/sign-donation-set.mjs. PUBLIC BYTES ONLY: each test
// network's donation set, signed once offline by that network's Ed25519
// donation authority (the key genesis hashes into its network id). Two local
// test LNURL recipients at a fixed address - never a production recipient.
import { fromHex } from './hash.js';
import { decodeDonationSetBody } from './authority.js';

const signedSet = (body, signature) => ({ ...decodeDonationSetBody(fromHex(body)), signature: fromHex(signature) });

/** The two local test endpoints the sets name, in the order published. */
export const TEST_DONATION_ENDPOINTS = ${JSON.stringify(ENDPOINTS)};

export const TEST_DONATION_SET_REGTEST = signedSet(
  '${signed.regtest.body}',
  '${signed.regtest.signature}');

export const TEST_DONATION_SET_TESTNET4 = signedSet(
  '${signed.testnet4.body}',
  '${signed.testnet4.signature}');
`);
console.log(`wrote ${OUT.pathname}`);
