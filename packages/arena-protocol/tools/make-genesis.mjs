/** Generate test donation keys and write public genesis-ids.js */
import { generateKeyPairSync } from 'node:crypto';
import { mkdirSync, writeFileSync, chmodSync } from 'node:fs';
import { join } from 'node:path';
import { toHex } from '../src/hash.js';
import { computeNetworkId, genesisFor } from '../src/genesis.js';
import { computeGenesisConfigHash } from '../../nextblock/config/game-config.js';

const KEYDIR = process.env.ARENA_GENESIS_KEYS || '/mnt/bitcoin/blwp-genesis';
const OUT = new URL('../src/genesis-ids.js', import.meta.url);

function ed25519() {
  const { publicKey, privateKey } = generateKeyPairSync('ed25519');
  const pub = publicKey.export({ type: 'spki', format: 'der' }).subarray(-32);
  const raw = privateKey.export({ type: 'pkcs8', format: 'der' });
  return { pub, pkcs8: raw };
}

function saveKey(name, pair) {
  mkdirSync(KEYDIR, { recursive: true, mode: 0o700 });
  const p = join(KEYDIR, name);
  writeFileSync(p, pair.pkcs8);
  chmodSync(p, 0o600);
}

const configHash = computeGenesisConfigHash();
const networks = ['regtest', 'testnet4'];
const pubs = {};
const ids = {};

for (const n of networks) {
  const auth = ed25519();
  const rec = ed25519();
  saveKey(`${n}-authority.pkcs8`, auth);
  saveKey(`${n}-recovery.pkcs8`, rec);
  pubs[n] = { authority: auth.pub, recovery: rec.pub };
  ids[n] = computeNetworkId({
    genesis: genesisFor(n),
    authorityPubkey: auth.pub,
    recoveryPubkey: rec.pub,
  });
}

const src = `// Generated by tools/make-genesis.mjs. Public hashes and pubkeys only.
import { fromHex } from './hash.js';

export const GENESIS_CONFIG_HASH = fromHex('${toHex(configHash)}');
export const NETWORK_ID_REGTEST = fromHex('${toHex(ids.regtest)}');
export const NETWORK_ID_TESTNET4 = fromHex('${toHex(ids.testnet4)}');
export const AUTHORITY_PUBKEY_REGTEST = fromHex('${toHex(pubs.regtest.authority)}');
export const RECOVERY_PUBKEY_REGTEST = fromHex('${toHex(pubs.regtest.recovery)}');
export const AUTHORITY_PUBKEY_TESTNET4 = fromHex('${toHex(pubs.testnet4.authority)}');
export const RECOVERY_PUBKEY_TESTNET4 = fromHex('${toHex(pubs.testnet4.recovery)}');
`;

writeFileSync(OUT, src);
console.log(JSON.stringify({
  keys: KEYDIR,
  genesisConfigHash: toHex(configHash),
  networkId: { regtest: toHex(ids.regtest), testnet4: toHex(ids.testnet4) },
}, null, 2));
