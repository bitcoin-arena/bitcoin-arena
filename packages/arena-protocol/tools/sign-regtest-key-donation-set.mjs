/**
 * REGTEST'S DONATION SET OF KEYS: the protocol devs' set a regtest round pays its donation half to when the
 * test hands its nodes a set of keys - the same two dev keys and shares as testnet4's key set (dev a 6667, dev b 3333), on
 * regtest's network id, signed offline by regtest's Ed25519 donation authority (refused if the key is not the one regtest
 * genesis names), serial 2 above the LNURL test set's 1, in force from height 0. Only a node handed this set reads it.
 *
 *   node packages/arena-protocol/tools/sign-regtest-key-donation-set.mjs        (ARENA_GENESIS_KEYS, default /mnt/bitcoin/blwp-genesis)
 *
 * Writes src/test-donation-set-keys-regtest.js - PUBLIC BYTES ONLY.
 */
import { createPrivateKey, createPublicKey, sign, verify } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { toHex } from '../src/hash.js';
import { NETWORK_ID_REGTEST, AUTHORITY_PUBKEY_REGTEST } from '../src/genesis-ids.js';
import { encodeDonationSetBody, decodeDonationSetBody, donationSetBodyId } from '../src/authority.js';
import { donationSetId } from '../src/donation.js';
import { TESTNET4_DONATION_SET_KEYS } from '../src/testnet4-donation-set-keys.js';

const KEYDIR = process.env.ARENA_GENESIS_KEYS || '/mnt/bitcoin/blwp-genesis';
const OUT = new URL('../src/test-donation-set-keys-regtest.js', import.meta.url);
const RECIPIENTS = TESTNET4_DONATION_SET_KEYS.recipients.map((r) => ({ recipientPk: r.recipientPk, shareBps: r.shareBps, label: r.label }));
const key = createPrivateKey({ key: readFileSync(join(KEYDIR, 'regtest-authority.pkcs8')), format: 'der', type: 'pkcs8' });
if (key.asymmetricKeyType !== 'ed25519') throw new Error('the regtest donation authority key is not Ed25519');
const pub = createPublicKey(key);
if (toHex(pub.export({ type: 'spki', format: 'der' }).subarray(-32)) !== toHex(AUTHORITY_PUBKEY_REGTEST))
  throw new Error('that key is not the donation authority regtest genesis names');
const body = { networkId: NETWORK_ID_REGTEST, serial: 2n, validFrom: 0, recipients: RECIPIENTS };
const bytes = encodeDonationSetBody(body);
const digest = Buffer.from(donationSetBodyId(body));
const signature = sign(null, digest, key);
if (!verify(null, digest, pub, signature)) throw new Error('the signature does not verify');
decodeDonationSetBody(bytes);
writeFileSync(OUT, `// Generated by tools/sign-regtest-key-donation-set.mjs. PUBLIC BYTES ONLY: regtest's donation set of KEYS,
// signed offline by regtest's Ed25519 donation authority, serial 2, in force from height 0 - testnet4's key set's two dev keys
// and shares on regtest's network id. Only a node handed this set reads it.
import { fromHex } from './hash.js';
import { decodeDonationSetBody } from './authority.js';

export const TEST_DONATION_SET_KEYS_REGTEST = { ...decodeDonationSetBody(fromHex('${toHex(bytes)}')),
  signature: fromHex('${toHex(signature)}') };
`);
console.log(JSON.stringify({ serial: 2, setId: toHex(donationSetId(RECIPIENTS)), recipients: RECIPIENTS.map((r) => [r.label, toHex(r.recipientPk).slice(0, 12), r.shareBps]), wrote: OUT.pathname }));
