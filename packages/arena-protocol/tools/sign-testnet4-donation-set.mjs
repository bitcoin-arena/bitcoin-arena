/**
 * THE TESTNET4 DONATION SET WITH REAL RECIPIENTS (LNURL-0822, 2026-10-02: "The donation set on testnet4 must use real
 * LNURL addresses. Not a placeholder. Not an address nothing reachable can pay. Use the local testnet4 LNDs").
 *
 *   node packages/arena-protocol/tools/sign-testnet4-donation-set.mjs
 *
 * Signs, with testnet4's donation authority (the key genesis hashes into its network id; refused if it is not), a set with
 * serial 2 - above the test set's 1, so it is the one in force (27A.4: the highest validly signed serial wins) - naming two
 * LNURL-pay endpoints reachable from anywhere, each minting invoices on one of the local testnet4 LNDs. Shares 6667 / 3333
 * as before. A round names its set by id in its contract (22A), so contracts already written keep the set they named; this
 * one is for the contracts written after it. Writes src/testnet4-donation-set.js - PUBLIC BYTES ONLY.
 */
import { createPrivateKey, createPublicKey, sign, verify } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { toHex } from '../src/hash.js';
import { NETWORK_ID_TESTNET4, AUTHORITY_PUBKEY_TESTNET4 } from '../src/genesis-ids.js';
import { encodeDonationSetBody, donationSetBodyId } from '../src/authority.js';
import { lnurlFor } from '../src/bech32.js';

const KEYDIR = process.env.ARENA_GENESIS_KEYS || '/mnt/bitcoin/blwp-genesis';
const OUT = new URL('../src/testnet4-donation-set.js', import.meta.url);
const BASE = 'https://beelink.tail1723e2.ts.net/lnurlp/';
const ENDPOINTS = [`${BASE}blwp-donate-a`, `${BASE}blwp-donate-b`];
const RECIPIENTS = [{ lnurl: lnurlFor(ENDPOINTS[0]), shareBps: 6667 }, { lnurl: lnurlFor(ENDPOINTS[1]), shareBps: 3333 }];

const key = createPrivateKey({ key: readFileSync(join(KEYDIR, 'testnet4-authority.pkcs8')), format: 'der', type: 'pkcs8' });
if (key.asymmetricKeyType !== 'ed25519') throw new Error('the testnet4 donation authority key is not Ed25519');
const pub = createPublicKey(key);
if (toHex(pub.export({ type: 'spki', format: 'der' }).subarray(-32)) !== toHex(AUTHORITY_PUBKEY_TESTNET4))
  throw new Error('that key is not the donation authority testnet4 genesis names');
// IN FORCE FROM VALID_FROM (a soft fork, 27A.4: the highest validly signed serial whose valid_from a round's census height has
// reached is the set that round must name; every paid series already published - census 154206, 154539, 154668 - keeps
// the set it named, 22A)
const VALID_FROM = Number(process.env.VALID_FROM || 154777);
const body = { networkId: NETWORK_ID_TESTNET4, serial: 2n, validFrom: VALID_FROM, recipients: RECIPIENTS };
const digest = Buffer.from(donationSetBodyId(body));
const signature = sign(null, digest, key);
if (!verify(null, digest, pub, signature)) throw new Error('the signature does not verify');
writeFileSync(OUT, `// Generated by tools/sign-testnet4-donation-set.mjs. PUBLIC BYTES ONLY: testnet4's donation set with real recipients
// (LNURL-0822), signed offline by testnet4's Ed25519 donation authority, serial 2. Two LNURL-pay endpoints reachable from
// anywhere, minting invoices on the two local testnet4 LNDs.
import { fromHex } from './hash.js';
import { decodeDonationSetBody } from './authority.js';

/** The two endpoints the set names, in the order published. */
export const TESTNET4_DONATION_ENDPOINTS = ${JSON.stringify(ENDPOINTS)};

export const TESTNET4_DONATION_SET = { ...decodeDonationSetBody(fromHex('${toHex(encodeDonationSetBody(body))}')),
  signature: fromHex('${toHex(signature)}') };
`);
console.log(`testnet4 set serial 2 signed by ${toHex(AUTHORITY_PUBKEY_TESTNET4).slice(0, 16)}: ${toHex(signature).slice(0, 16)}...; wrote ${OUT.pathname}`);
