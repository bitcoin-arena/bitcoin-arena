// WRITES packages/arena-protocol/src/known-games.js (kanban #202, #203; §0A.6, §5): the games this client lets a player stake
// on - each by game_id, with the cores and configs its signed manifest lists and the configs it plays as one world per
// round. It imports no game: each game is a module GIVEN AS AN ARGUMENT that exports
// KNOWN_GAME = { manifestHex, sharedWorld } (nextblock's: packages/nextblock/plugin/known.js).
//
//   node packages/arena-protocol/tools/known-games.js packages/nextblock/plugin/known.js [more games ...]
//
// A game already listed stays listed (a round already written on its manifest is still known).
import { existsSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { decodeManifest, gameIdOf, isAttested } from '../src/manifest.js';
import { toHex, fromHex } from '../src/hash.js';

const OUT = new URL('../src/known-games.js', import.meta.url).pathname;
const args = process.argv.slice(2);
if (!args.length) { console.error('usage: node known-games.js <game module exporting KNOWN_GAME> ...'); process.exit(2); }
const prior = existsSync(OUT) ? (await import(OUT)) : { KNOWN_GOOD_GAMES: {} };
const games = Object.fromEntries(Object.entries(prior.KNOWN_GOOD_GAMES).map(([id, g]) => [id, { name: g.name, cores: g.cores, sharedWorld: g.sharedWorld || [],
  gameDonationSetId: g.gameDonationSetId, ...(g.attested ? { attested: g.attested } : {}), ...(g.fee ? { fee: g.fee } : {}), ...(g.terms ? { terms: g.terms } : {}),
  ...(g.requiredProtocolVersion ? { requiredProtocolVersion: g.requiredProtocolVersion } : {}) }]));
for (const path of args) {
  const { KNOWN_GAME } = await import(pathToFileURL(resolve(path)).href);
  const m = decodeManifest(fromHex(KNOWN_GAME.manifestHex));
  games[toHex(gameIdOf(m))] = { name: m.gameName, cores: Object.fromEntries(m.cores.map((c) => [toHex(c.hash), c.configs.map(toHex)])),
    sharedWorld: [...(KNOWN_GAME.sharedWorld || [])], gameDonationSetId: toHex(m.gameDonationSetId),
    // AN ATTESTED GAME (§0A.7a, kanban #206 slice 2): its outcomes, attestors and threshold, from its signed manifest, and the
    // networks it is pinned for (a market pinned for regtest is refused on any other network)
    ...(isAttested(m) ? { attested: { outcomes: [...m.outcomes], attestors: m.attestors.map(toHex), threshold: m.attestThreshold,
      devKey: toHex(m.gameDevPubkey), networks: [...(KNOWN_GAME.networks || [])] } } : {}),
    // A MARKET'S OWN FEE (kanban #235), when its manifest names one; without it the page charges the market default (known-game.js)
    ...(m.marketTerms ? { fee: { nodeBps: m.marketTerms.nodeFeeBps, donationBps: m.marketTerms.donationBps } } : {}),
    // AND ITS TERMS' CLOCK (kanban #236): resolution delay and void deadline, which its rounds' lock span is checked by
    ...(m.marketTerms ? { terms: { resolveAfterCloseMs: String(m.marketTerms.resolveAfterCloseMs), deadlineAfterResolveMs: String(m.marketTerms.deadlineAfterResolveMs) } } : {}),
    // THE PROTOCOL VERSION IT REQUIRES (kanban #349), when its manifest names one
    ...(m.requiredProtocolVersion ? { requiredProtocolVersion: m.requiredProtocolVersion } : {}) };
}
const list = (xs) => xs.map((x) => `'${x}'`).join(', ');
writeFileSync(OUT, `// GENERATED by packages/arena-protocol/tools/known-games.js from each game's signed manifest - do not edit by hand.
//
// The games this client lets a player stake on (§0A.6, §5; kanban #202), by game_id: each with the cores (sim_wasm_hash)
// and, per core, the configs its manifest lists, and the configs the game plays as one world per round (seed.js asks
// them through known-game.js sharedWorldOf; kanban #203). A paying round naming any other game, or a core or config its
// game does not list, is refused by \`gameIsKnownGood\` (known-game.js).
export const KNOWN_GOOD_GAMES = Object.freeze({
${Object.entries(games).map(([id, g]) => `  '${id}': Object.freeze({
    name: '${g.name}',
    cores: Object.freeze({
${Object.entries(g.cores).map(([c, cs]) => `      '${c}': Object.freeze([${list(cs)}]),`).join('\n')}
    }),
    sharedWorld: Object.freeze([${list(g.sharedWorld)}]),
    gameDonationSetId: '${g.gameDonationSetId}',${g.attested ? `
    attested: Object.freeze({ outcomes: Object.freeze(${JSON.stringify(g.attested.outcomes).replace(/"/g, "'")}), attestors: Object.freeze([${list(g.attested.attestors)}]),
      threshold: ${g.attested.threshold}, devKey: '${g.attested.devKey}', networks: Object.freeze([${list(g.attested.networks)}]) }),` : ''}${g.fee ? `
    fee: Object.freeze({ nodeBps: ${g.fee.nodeBps}, donationBps: ${g.fee.donationBps} }),` : ''}${g.terms ? `
    terms: Object.freeze({ resolveAfterCloseMs: '${g.terms.resolveAfterCloseMs}', deadlineAfterResolveMs: '${g.terms.deadlineAfterResolveMs}' }),` : ''}${g.requiredProtocolVersion ? `
    requiredProtocolVersion: ${g.requiredProtocolVersion},` : ''}
  }),`).join('\n')}
});
`);
console.log(`${Object.keys(games).length} game(s) listed: ${Object.values(games).map((g) => `${g.name} (${g.sharedWorld.length} shared-world config)`).join(', ')}`);
