// THE DEV CLIENT'S MANIFEST STEP (kanban #202, Daniel 2026-10-07 15:40): signs a game's manifest with the game
// developer's key, held in the dev client's own directory, and writes only public bytes - the body (with the public key)
// and the signature - into the game's package. Run by the game's developer, never on a seat; a seat only verifies.
//
//   node packages/blwp-donor/bin/sign-game-manifest.mjs nextblock <dev dir>
//
// The key is <dev dir>/game-dev.pkcs8 (Ed25519, PKCS#8 DER, mode 600). For nextblock the body is its registration's own
// (core/plugin/truck-cores.js nextblockManifestBody): every installed core with its configs, the game's client scripts
// as blwp-client/known-good-clients.json lists them for nextblock, and the donation set the testnet4 series name. Run it
// again whenever a core, a config or a client of nextblock changes: an update is a new manifest (§0A.3), and
// core/test/nextblock-manifest.test.js is red until the signed bytes are the registration's.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { gameDevKey, signManifest } from '../src/manifest-sign.js';
import { nextblockManifestBody } from '../../core/plugin/truck-cores.js';
import { encodeManifest, gameIdOf, manifestStands } from '../../protocol/src/manifest.js';
import { donationSetId } from '../../protocol/src/donation.js';
import { TESTNET4_DONATION_SET_KEYS } from '../../protocol/src/testnet4-donation-set-keys.js';
import { toHex } from '../../protocol/src/hash.js';
import { verifyEd25519 } from '../../blwp-node/src/ed25519.js';

const [game, dir] = process.argv.slice(2);
if (game !== 'nextblock' || !dir) {
  console.error('usage: node sign-game-manifest.mjs nextblock <dev dir holding game-dev.pkcs8>');
  process.exit(2);
}
const dev = gameDevKey(readFileSync(join(dir, 'game-dev.pkcs8')));
const LIST = JSON.parse(readFileSync(new URL('../../blwp-client/known-good-clients.json', import.meta.url), 'utf8'));
const body = nextblockManifestBody({ clients: LIST.games.nextblock.pinned['blwp-core.js'], gameDevPubkey: dev.pubkey,
  gameDonationSetId: donationSetId(TESTNET4_DONATION_SET_KEYS.recipients) });
const manifest = signManifest(body, dev);
// AS A NODE WILL CHECK IT: the same verifier, the same rule
const stands = manifestStands(manifest, { verify: verifyEd25519 });
if (!stands.ok) throw new Error(stands.why);

const OUT = new URL('../../core/plugin/nextblock-manifest.js', import.meta.url);
writeFileSync(OUT, `// GENERATED by packages/blwp-donor/bin/sign-game-manifest.mjs, the dev client - do not edit by hand. PUBLIC BYTES ONLY:
// nextblock's GameManifest (§0A.3), its body and the 64-byte signature by its developer key
// ${toHex(dev.pubkey)}.
// A node verifies this signature (blwp-node/src/plugins.js); it never holds the key and never signs.
// game_id ${toHex(gameIdOf(manifest))}
export const NEXTBLOCK_MANIFEST_HEX = '${toHex(encodeManifest(manifest))}';
`);
console.log(`nextblock v${body.version}: ${body.cores.length} cores, ${body.clients.length} clients; game_id ${toHex(gameIdOf(manifest))}`);
