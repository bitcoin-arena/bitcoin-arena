// ROCK PAPER SCISSORS' MANIFEST VERSION 3, SIGNED BY ITS DEVELOPER (2026-10-16: "everywhere where you added
// < games as navigation it needs to say Arena"): version 2 in every term, with its new client ("← Arena") beside version 2's,
// so either file runs a round of it. Parent: version 2 (plugin/rock-paper-scissors-v2.js).
//
//   node packages/rock-paper-scissors/tools/sign-manifest-v3.mjs <dev dir holding game-dev.pkcs8>
//
// Writes only public bytes: plugin/rock-paper-scissors-v3.js.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { createHash } from 'node:crypto';
import { gameDevKey, signManifest } from 'arena-sdk/manifest-sign';
import { MANIFEST_V2, GAME_ID_V2 } from '../plugin/rock-paper-scissors-v2.js';
import { RPS_CLIENT_FILE, RPS_CLIENT_V3_FILE } from '../plugin/rock-paper-scissors.js';
import { encodeManifest, gameIdOf, manifestStands } from 'arena-sdk/manifest';
import { toHex } from 'arena-sdk/hash';
import { verifyEd25519 } from 'arena-sdk/ed25519';

const [dir] = process.argv.slice(2);
if (!dir) { console.error('usage: node sign-manifest-v3.mjs <dev dir holding game-dev.pkcs8>'); process.exit(2); }
const dev = gameDevKey(readFileSync(join(dir, 'game-dev.pkcs8')));
if (toHex(dev.pubkey) !== toHex(MANIFEST_V2.gameDevPubkey)) throw new Error(`that key is not Rock Paper Scissors' developer key ${toHex(MANIFEST_V2.gameDevPubkey).slice(0, 16)}`);
const hash = (u) => new Uint8Array(createHash('sha256').update(readFileSync(u)).digest());
const OLD = hash(RPS_CLIENT_FILE), NEW = hash(RPS_CLIENT_V3_FILE);
if (!MANIFEST_V2.clients.some((c) => toHex(c) === toHex(OLD))) throw new Error('client/index-v2.html is not a file version 2 pins');
const { signature, ...v2body } = MANIFEST_V2;
void signature;
const body = { ...v2body, version: MANIFEST_V2.version + 1, parentManifestId: GAME_ID_V2,
  clients: [...new Map([NEW, ...MANIFEST_V2.clients].map((c) => [toHex(c), c])).values()].sort((x, y) => Buffer.compare(Buffer.from(x), Buffer.from(y))) };
const manifest = signManifest(body, dev);
const stands = manifestStands(manifest, { verify: verifyEd25519, parentOf: (id) => (toHex(id) === toHex(GAME_ID_V2) ? MANIFEST_V2 : null) });
if (!stands.ok) throw new Error(stands.why);
const id = toHex(gameIdOf(manifest));
writeFileSync(new URL('../plugin/rock-paper-scissors-v3.js', import.meta.url), `// GENERATED by packages/rock-paper-scissors/tools/sign-manifest-v3.mjs with the dev client's signer - do not edit by hand. PUBLIC BYTES ONLY:
// rock-paper-scissors' GameManifest version 3: version 2 (${toHex(GAME_ID_V2)}) in every term, with the new client
// ${toHex(NEW)} ("← Arena") beside version 2's; requires protocol version ${body.requiredProtocolVersion}.
// Signed by its developer key ${toHex(dev.pubkey)}; a node verifies it and never signs.
// game_id ${id}
import { GAME as V1, RPS_CLIENT_V3_FILE } from './rock-paper-scissors.js';
import { decodeManifest, gameIdOf } from 'arena-sdk/manifest';
import { fromHex } from 'arena-sdk/hash';

export const MANIFEST_V3_HEX = '${toHex(encodeManifest(manifest))}';
export const MANIFEST_V3 = decodeManifest(fromHex(MANIFEST_V3_HEX));
export const GAME_ID_V3 = gameIdOf(MANIFEST_V3);
/** What a launcher loads from this module (ARENA_GAMES): the registration, its client the new file. */
export const GAME = Object.freeze({ ...V1, manifest: MANIFEST_V3, gameId: GAME_ID_V3, clientUrls: [RPS_CLIENT_V3_FILE.href] });
`);
console.log(`rock-paper-scissors v${body.version}: parent ${toHex(GAME_ID_V2).slice(0, 16)}, clients ${body.clients.map((c) => toHex(c).slice(0, 8)).join(' ')}, game_id ${id}`);
