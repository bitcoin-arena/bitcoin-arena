// ROCK PAPER SCISSORS' MANIFEST VERSION 4, SIGNED BY ITS DEVELOPER: version 3 in every term but its core and its client - the core
// plugin/decide-v4.js (the same rules, its comment without names or ticket numbers) and the client client/index-v4.html (the table drawn
// by React, written by tools/build-client-v4.mjs). Parent: version 3 (plugin/rock-paper-scissors-v3.js).
//
//   node packages/rock-paper-scissors/tools/sign-manifest-v4.mjs <dev dir holding game-dev.pkcs8>
//
// Writes only public bytes: plugin/rock-paper-scissors-v4.js.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { createHash } from 'node:crypto';
import { gameDevKey, signManifest } from 'arena-sdk/manifest-sign';
import { MANIFEST_V3, GAME_ID_V3 } from '../plugin/rock-paper-scissors-v3.js';
import { encodeManifest, gameIdOf, manifestStands } from 'arena-sdk/manifest';
import { toHex } from 'arena-sdk/hash';
import { verifyEd25519 } from 'arena-sdk/ed25519';

const [dir] = process.argv.slice(2);
if (!dir) { console.error('usage: node sign-manifest-v4.mjs <dev dir holding game-dev.pkcs8>'); process.exit(2); }
const dev = gameDevKey(readFileSync(join(dir, 'game-dev.pkcs8')));
if (toHex(dev.pubkey) !== toHex(MANIFEST_V3.gameDevPubkey)) throw new Error(`that key is not Rock Paper Scissors' developer key ${toHex(MANIFEST_V3.gameDevPubkey).slice(0, 16)}`);
const hash = (u) => new Uint8Array(createHash('sha256').update(readFileSync(u)).digest());
const CORE = hash(new URL('../plugin/decide-v4.js', import.meta.url));
const CLIENT = hash(new URL('../client/index-v4.html', import.meta.url));
const { signature, ...v3body } = MANIFEST_V3;
void signature;
if (MANIFEST_V3.cores.length !== 1) throw new Error('version 3 names one core');
const body = { ...v3body, version: MANIFEST_V3.version + 1, parentManifestId: GAME_ID_V3, cores: [{ ...MANIFEST_V3.cores[0], hash: CORE }], clients: [CLIENT] };
const manifest = signManifest(body, dev);
const stands = manifestStands(manifest, { verify: verifyEd25519, parentOf: (id) => (toHex(id) === toHex(GAME_ID_V3) ? MANIFEST_V3 : null) });
if (!stands.ok) throw new Error(stands.why);
const id = toHex(gameIdOf(manifest));
writeFileSync(new URL('../plugin/rock-paper-scissors-v4.js', import.meta.url), `// GENERATED by packages/rock-paper-scissors/tools/sign-manifest-v4.mjs with the dev client's signer - do not edit by hand. PUBLIC BYTES ONLY:
// rock-paper-scissors' GameManifest version 4: version 3 (${toHex(GAME_ID_V3)}) in every term but its core
// ${toHex(CORE)} (plugin/decide-v4.js) and its client ${toHex(CLIENT)} (client/index-v4.html); requires protocol version
// ${body.requiredProtocolVersion}. Signed by its developer key ${toHex(dev.pubkey)}; a node verifies it and never signs.
// game_id ${id}
import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { GAME as V1 } from './rock-paper-scissors.js';
import { decodeManifest, gameIdOf } from 'arena-sdk/manifest';
import { fromHex } from 'arena-sdk/hash';

export const MANIFEST_V4_HEX = '${toHex(encodeManifest(manifest))}';
export const MANIFEST_V4 = decodeManifest(fromHex(MANIFEST_V4_HEX));
export const GAME_ID_V4 = gameIdOf(MANIFEST_V4);
const sha = (b) => createHash('sha256').update(b).digest('hex');
const DECIDE_V4_URL = new URL('./decide-v4.js', import.meta.url);
const requireCore = createRequire(import.meta.url);
/** Its one core: the decide adapter of plugin/decide-v4.js, run in the node's sandbox from that file, checked against its hash. */
export const RPS_DECIDE_V4_CORE = Object.freeze(Object.defineProperty({ name: 'rock-paper-scissors decide v1', hash: sha(readFileSync(DECIDE_V4_URL)), url: DECIDE_V4_URL.href,
  configs: new Map([[sha('rock-paper-scissors-config:v1'), {}]]) }, 'adapter', { get: () => requireCore('./decide-v4.js').DECIDE, enumerable: false }));
export const RPS_CLIENT_V4_FILE = new URL('../client/index-v4.html', import.meta.url);
/** What a launcher loads from this module (ARENA_APPS): the registration, its core and its client version 4's. */
export const GAME = Object.freeze({ ...V1, manifest: MANIFEST_V4, gameId: GAME_ID_V4, cores: new Map([[RPS_DECIDE_V4_CORE.hash, RPS_DECIDE_V4_CORE]]), clientUrls: [RPS_CLIENT_V4_FILE.href] });
/** A version-4 round's fields: its game, its core and config, the timing of versions 1 to 3. */
export const RPS_ROUND_FIELDS_V4 = Object.freeze({ gameId: GAME_ID_V4, simCoreHash: fromHex(RPS_DECIDE_V4_CORE.hash),
  configHash: fromHex([...RPS_DECIDE_V4_CORE.configs.keys()][0]), blockTicks: 600, startDeadlineTicks: 300, minScore: 2 });
`);
console.log(`rock-paper-scissors v${body.version}: parent ${toHex(GAME_ID_V3).slice(0, 16)}, core ${toHex(CORE).slice(0, 12)}, client ${toHex(CLIENT).slice(0, 12)}, game_id ${id}`);
